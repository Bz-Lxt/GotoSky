type row struct {
	ID, Name, ZH, Kind string
	RA, Dec, Mag, Size float64
}

// Catalog returns 130 deep-sky objects (110 Messier + 20 NGC/IC).
func Catalog() []domain.Target {
	rows := messier()
	rows = append(rows, extraNGC()...)
	out := make([]domain.Target, 0, len(rows))
	for _, r := range rows {
		mag, sz := r.Mag, r.Size
		out = append(out, domain.Target{
			ID: uuid.NewSHA1(uuid.NameSpaceOID, []byte(r.ID)),
			CatalogID: r.ID, Name: r.Name, NameZH: r.ZH,
			RAHours: r.RA, DecDeg: r.Dec, Mag: &mag, Kind: r.Kind, SizeArcmin: &sz,
		})
	}
	return out
}

